    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: shipping_info
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS shipping_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    tracking_number TEXT,
    carrier TEXT,
    shipping_url TEXT,
    status TEXT DEFAULT 'preparing', -- preparing, shipped, in_transit, out_for_delivery, delivered
    estimated_delivery DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: fund_pool
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS fund_pool (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
    amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    status TEXT DEFAULT 'frozen', -- frozen, available, distributed
    frozen_until TIMESTAMPTZ NOT NULL, -- Date où les fonds deviennent disponibles (payement + 14 jours)
    released_at TIMESTAMPTZ,
    distributed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: dividend_distributions
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS dividend_distributions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distribution_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    total_amount DECIMAL(10,2) NOT NULL,
    admin1_share DECIMAL(10,2) NOT NULL,
    admin2_share DECIMAL(10,2) NOT NULL,
    admin1_stripe_transfer_id TEXT,
    admin2_stripe_transfer_id TEXT,
    status TEXT DEFAULT 'pending', -- pending, completed, failed
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: refunds
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    stripe_refund_id TEXT,
    amount DECIMAL(10,2) NOT NULL,
    reason TEXT,
    status TEXT DEFAULT 'pending', -- pending, approved, rejected, completed
    requested_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    approved_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: profiles (pour étendre auth.users)
