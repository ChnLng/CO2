-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: products
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    price DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    image_url TEXT,
    stock INTEGER DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE,
    weight_grams INTEGER DEFAULT 0, -- Pour calcul des frais de livraison
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: shipping_rates
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS shipping_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone TEXT NOT NULL, -- "france", "europe", "international"
    min_weight_grams INTEGER DEFAULT 0,
    max_weight_grams INTEGER,
    base_price DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    price_per_kg DECIMAL(10,2) DEFAULT 0.00,
    carrier TEXT NOT NULL DEFAULT 'cainiao', -- cainiao, la poste, etc.
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: promo_codes
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS promo_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    discount_percent INTEGER NOT NULL DEFAULT 0,
    valid_from TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    valid_until TIMESTAMPTZ,
    max_uses INTEGER,
    times_used INTEGER DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: orders
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    stripe_payment_intent_id TEXT,
    
    -- Montants
    subtotal DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    shipping_cost DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    discount_amount DECIMAL(10,2) DEFAULT 0.00,
    tax_amount DECIMAL(10,2) DEFAULT 0.00,
    total_amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    
    promo_code_id BIGINT REFERENCES promo_codes(id) ON DELETE SET NULL,
    status TEXT DEFAULT 'pending', -- pending, paid, shipped, delivered, cancelled, refunded
    
    -- Adresse de livraison
    shipping_name TEXT NOT NULL,
    shipping_email TEXT NOT NULL,
    shipping_phone TEXT NOT NULL,
    shipping_address TEXT NOT NULL,
    shipping_city TEXT NOT NULL,
    shipping_postal_code TEXT NOT NULL,
    shipping_country TEXT NOT NULL,
    
    -- Dates importantes
    paid_at TIMESTAMPTZ,
    shipped_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    refunded_at TIMESTAMPTZ,
    
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --- --- --- --- --- --- --- --- --- --- --- 
-- Table: order_items
-- --- --- --- --- --- --- --- --- --- --- --- 
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
