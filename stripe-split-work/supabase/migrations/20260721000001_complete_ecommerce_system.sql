CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, email, phone, role)
  VALUES (
    new.id, 
    new.email, 
    COALESCE(new.raw_user_meta_data->>'phone', ''),
    'customer'
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ==============================================
-- 7. FONCTION DE CALCUL DES FRAIS DE LIVRAISON
-- ==============================================
CREATE OR REPLACE FUNCTION calculate_shipping_cost(
    zone TEXT, 
    total_weight_grams INTEGER
) 
RETURNS DECIMAL(10,2) AS $$
DECLARE
    cost DECIMAL(10,2);
BEGIN
    SELECT 
        base_price + (GREATEST(0, (total_weight_grams / 1000.0 - 1)) * price_per_kg)
    INTO cost
    FROM shipping_rates
    WHERE 
        shipping_rates.zone = calculate_shipping_cost.zone
        AND shipping_rates.min_weight_grams <= total_weight_grams
        AND (shipping_rates.max_weight_grams IS NULL OR shipping_rates.max_weight_grams >= total_weight_grams)
        AND shipping_rates.is_active = TRUE
    ORDER BY shipping_rates.id ASC
    LIMIT 1;
    
    RETURN COALESCE(cost, 0.00);
END;
$$ LANGUAGE plpgsql;

-- ==============================================
-- 8. FONCTION POUR OBTENIR LE PRIX APRÈS PROMO
-- ==============================================
CREATE OR REPLACE FUNCTION apply_promo_code(
    promo_code_id BIGINT, 
    original_amount DECIMAL(10,2)
) 
RETURNS DECIMAL(10,2) AS $$
DECLARE
    discount_percent_val INTEGER;
    discount_amount_val DECIMAL(10,2);
BEGIN
    IF promo_code_id IS NULL THEN
        RETURN 0.00;
    END IF;
    
    SELECT discount_percent INTO discount_percent_val
    FROM promo_codes
    WHERE id = promo_code_id
        AND is_active = TRUE
        AND valid_from <= NOW()
        AND (valid_until IS NULL OR valid_until >= NOW())
        AND (max_uses IS NULL OR times_used < max_uses);
        
    IF discount_percent_val IS NULL THEN
        RETURN 0.00;
    END IF;
    
    discount_amount_val := original_amount * (discount_percent_val / 100.0);
    RETURN discount_amount_val;
END;
$$ LANGUAGE plpgsql;

-- ==============================================
-- 9. FONCTION POUR INCÉMENTER L'UTILISATION D'UN PROMO CODE
-- ==============================================
CREATE OR REPLACE FUNCTION increment_promo_code_usage(promo_id BIGINT)
RETURNS void AS $$
BEGIN
    UPDATE promo_codes 
    SET times_used = times_used + 1 
    WHERE id = promo_id;
END;
$$ LANGUAGE plpgsql;

