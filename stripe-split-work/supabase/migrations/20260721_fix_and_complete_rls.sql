-- 修复和完善数据库 RLS 策略及缺失的功能

-- 1. 首先确保所有必要的表都存在
CREATE TYPE IF NOT EXISTS after_sales_status AS ENUM ('pending', 'in_review', 'resolved', 'cancelled');

-- 创建 Profile 表（如果不存在）
CREATE TABLE IF NOT EXISTS profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT DEFAULT 'user',
    full_name TEXT,
    phone TEXT,
    address TEXT,
    city TEXT,
    postal_code TEXT,
    country TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 创建售后表（如果不存在）
CREATE TABLE IF NOT EXISTS after_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    subject TEXT NOT NULL,
    description TEXT NOT NULL,
    status after_sales_status DEFAULT 'pending',
    admin_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. 启用所有表的 RLS
ALTER TABLE IF EXISTS profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS after_sales ENABLE ROW LEVEL SECURITY;

-- 3. 创建或更新所有 RLS 策略

-- Profile 策略
DROP POLICY IF EXISTS "Users can view their own profile" ON profiles;
CREATE POLICY "Users can view their own profile" 
    ON profiles FOR SELECT 
    USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update their own profile" ON profiles;
CREATE POLICY "Users can update their own profile" 
    ON profiles FOR UPDATE 
    USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can insert their own profile" ON profiles;
CREATE POLICY "Users can insert their own profile" 
    ON profiles FOR INSERT 
    WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Authenticated users can view all profiles" ON profiles;
CREATE POLICY "Authenticated users can view all profiles" 
    ON profiles FOR SELECT 
    USING (auth.role() = 'authenticated');

-- After-sales 策略
DROP POLICY IF EXISTS "Users can view their own after-sales" ON after_sales;
CREATE POLICY "Users can view their own after-sales" 
    ON after_sales FOR SELECT 
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own after-sales" ON after_sales;
CREATE POLICY "Users can insert their own after-sales" 
    ON after_sales FOR INSERT 
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Authenticated users can manage after-sales" ON after_sales;
CREATE POLICY "Authenticated users can manage after-sales" 
    ON after_sales FOR ALL 
    USING (auth.role() = 'authenticated');

